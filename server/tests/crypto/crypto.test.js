// M1 — FR-11 extension: hybrid ballot encryption and the election public key API.
import nodeCrypto from 'node:crypto';
import { describe, it, expect, beforeAll, beforeEach } from 'vitest';
import { query } from '../../src/core/db.js';
import {
  encryptBallot,
  decryptBallot,
  keyPairMatches,
  fingerprint,
} from '../../src/modules/crypto/index.js';
import { resetDb, agent, createAdmin, createElection, loginAdmin, createVoter, loginVoter } from '../helpers.js';

function nodeKeyPair(bits = 2048) {
  return nodeCrypto.generateKeyPairSync('rsa', {
    modulusLength: bits,
    publicKeyEncoding: { type: 'spki', format: 'pem' },
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
  });
}

/** Same steps the EC's browser runs (Web Crypto), so we know the two sides agree. */
async function browserKeyPair() {
  const { subtle } = globalThis.crypto;
  const pair = await subtle.generateKey(
    { name: 'RSA-OAEP', modulusLength: 3072, publicExponent: new Uint8Array([1, 0, 1]), hash: 'SHA-256' },
    true,
    ['encrypt', 'decrypt'],
  );
  const pem = (label, buf) =>
    `-----BEGIN ${label}-----\n${Buffer.from(buf).toString('base64').match(/.{1,64}/g).join('\n')}\n-----END ${label}-----\n`;
  return {
    publicKey: pem('PUBLIC KEY', await subtle.exportKey('spki', pair.publicKey)),
    privateKey: pem('PRIVATE KEY', await subtle.exportKey('pkcs8', pair.privateKey)),
  };
}

const choices = [
  { positionId: 1, candidateId: 7 },
  { positionId: 2, candidateId: 19 },
];

describe('encryptBallot / decryptBallot', () => {
  let keys;
  beforeAll(() => {
    keys = nodeKeyPair();
  });

  it('round-trips the choices', () => {
    const blob = encryptBallot(choices, keys.publicKey);
    expect(blob.startsWith('v1.')).toBe(true);
    expect(blob).not.toContain('candidateId');
    expect(decryptBallot(blob, keys.privateKey)).toEqual(choices);
  });

  it('gives a different ciphertext every time (fresh AES key and IV)', () => {
    expect(encryptBallot(choices, keys.publicKey)).not.toBe(encryptBallot(choices, keys.publicKey));
  });

  it('pads ballots so their size does not reveal how many posts were filled', () => {
    const one = encryptBallot([{ positionId: 1, candidateId: 1 }], keys.publicKey);
    const many = encryptBallot(
      Array.from({ length: 28 }, (_, i) => ({ positionId: i + 1, candidateId: 1000 + i })),
      keys.publicKey,
    );
    expect(one.length).toBe(many.length);
  });

  it('refuses a tampered ballot and the wrong private key', () => {
    const blob = encryptBallot(choices, keys.publicKey);
    const parts = blob.split('.');
    const ct = Buffer.from(parts[4], 'base64url');
    ct[10] ^= 1;
    parts[4] = ct.toString('base64url');
    expect(() => decryptBallot(parts.join('.'), keys.privateKey)).toThrow();
    expect(() => decryptBallot(blob, nodeKeyPair().privateKey)).toThrow();
    expect(() => decryptBallot('garbage', keys.privateKey)).toThrow(/format/);
  });

  it('works with a key pair generated by the browser (Web Crypto)', async () => {
    const browser = await browserKeyPair();
    const blob = encryptBallot(choices, browser.publicKey);
    expect(decryptBallot(blob, browser.privateKey)).toEqual(choices);
    expect(keyPairMatches(browser.privateKey, browser.publicKey)).toBe(true);
    expect(keyPairMatches(keys.privateKey, browser.publicKey)).toBe(false);
  });

  it('rejects weak or non-RSA public keys', () => {
    const weak = nodeCrypto.generateKeyPairSync('rsa', {
      modulusLength: 1024,
      publicKeyEncoding: { type: 'spki', format: 'pem' },
      privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
    });
    const ec = nodeCrypto.generateKeyPairSync('ec', {
      namedCurve: 'P-256',
      publicKeyEncoding: { type: 'spki', format: 'pem' },
      privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
    });
    expect(() => encryptBallot(choices, weak.publicKey)).toThrow(/2048/);
    expect(() => encryptBallot(choices, ec.publicKey)).toThrow(/RSA/);
    expect(() => encryptBallot(choices, 'not a key')).toThrow(/valid public key/);
  });
});

describe('/api/admin/crypto/public-key', () => {
  let keys;
  beforeAll(() => {
    keys = nodeKeyPair();
  });
  beforeEach(resetDb);

  async function asEc() {
    const ec = await createAdmin({ email: 'ec@test.local' });
    const ag = agent();
    await loginAdmin(ag, ec).expect(200);
    return ag;
  }

  it('EC uploads the public key; it is stored, fingerprinted and audited', async () => {
    const election = await createElection();
    const ag = await asEc();

    const before = await ag.get('/api/admin/crypto/public-key').expect(200);
    expect(before.body.data.hasKey).toBe(false);

    const res = await ag.put('/api/admin/crypto/public-key').send({ publicKey: keys.publicKey }).expect(200);
    expect(res.body.data.fingerprint).toBe(fingerprint(keys.publicKey));

    const { rows } = await query('SELECT public_key FROM elections WHERE id = $1', [election.id]);
    expect(rows[0].public_key).toBe(keys.publicKey.trim());

    const audit = await query(`SELECT target FROM audit_log WHERE action = 'SET_PUBLIC_KEY'`);
    expect(audit.rows[0].target).toContain(res.body.data.fingerprint);
  });

  it('rejects an invalid key', async () => {
    await createElection();
    const ag = await asEc();
    const res = await ag
      .put('/api/admin/crypto/public-key')
      .send({ publicKey: 'x'.repeat(200) })
      .expect(400);
    expect(res.body.error.code).toBe('INVALID_PUBLIC_KEY');
  });

  it('cannot be changed once voting has started', async () => {
    await createElection({ startsInDays: -1, lengthDays: 2 });
    const ag = await asEc();
    const res = await ag.put('/api/admin/crypto/public-key').send({ publicKey: keys.publicKey }).expect(409);
    expect(res.body.error.code).toBe('ELECTION_LOCKED');
  });

  it('observers can read it but not change it; voters cannot see it', async () => {
    await createElection();
    const obs = await createAdmin({ email: 'obs@test.local', role: 'observer' });
    const ag = agent();
    await loginAdmin(ag, obs).expect(200);
    await ag.get('/api/admin/crypto/public-key').expect(200);
    await ag.put('/api/admin/crypto/public-key').send({ publicKey: keys.publicKey }).expect(403);

    const voter = await createVoter();
    const vag = agent();
    await loginVoter(vag, voter);
    await vag.get('/api/admin/crypto/public-key').expect(403);
  });
});
